#!/usr/bin/env python3
"""Regenerate the checked-in grayscale atlas; Pillow is needed only here.

No runtime font parser or host font dependency is introduced into the OS build.
The atlas contains ASCII, Latin-1, punctuation, and a replacement glyph.
"""
from pathlib import Path
import argparse
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/DejaVuSans.ttf"
OUT = ROOT / "render/desk_font.c"
POINTS = list(range(32, 127)) + list(range(160, 256)) + [0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x20ac, 0x2212, 0xfffd]


def generate(density):
    lines = ["/* Generated by tools/make_desktop_font.py; do not edit.",
             f" * DejaVu Sans SHA256: {hashlib.sha256(FONT.read_bytes()).hexdigest()}",
             " * Font license: assets/fonts/LICENSE-DejaVu.txt */",
             '#include <srvros/desk_render.h>',
             '#include "desk_font_2x.inc"',
             'const char desk_font_license[] = ' + json.dumps(
                 (FONT.parent / "LICENSE-DejaVu.txt").read_text()) + ';']
    if density==2:
        lines=["/* Generated native 2x coverage from bundled DejaVu fonts.",
               " * Regenerate: tools/make_desktop_font.py --density2-only",
               " * Font license: assets/fonts/LICENSE-DejaVu.txt */"]
    for name, size, source in (("16",16,FONT),("20",20,FONT),("mono_16",16,FONT.parent/"DejaVuSansMono.ttf"),("digits_32",32,FONT.parent/"DejaVuSansMono.ttf")):
        if source != FONT:
            lines.append(f"/* {source.name} SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()} */")
        font = ImageFont.truetype(str(source), size*density, layout_engine=ImageFont.Layout.BASIC)
        pixels, glyphs = [], []
        ascent, descent = font.getmetrics()
        points = sorted(set(POINTS + list(range(0x2500,0x2580)))) if source != FONT else POINTS
        if name == "digits_32":
            points = [32,46] + list(range(48,59)) + [0xfffd]
        for cp in points:
            char = chr(cp)
            x0, y0, x1, y1 = font.getbbox(char, anchor="ls")
            w, h = x1-x0, y1-y0
            offset = len(pixels)
            if w and h:
                im = Image.new("L", (w, h))
                ImageDraw.Draw(im).text((-x0, -y0), char, font=font, fill=255, anchor="ls")
                pixels.extend(im.tobytes())
            glyphs.append((cp, offset, w, h, x0, y0, round(font.getlength(char))))
        if density==2:name += "_2x"
        lines.append(f"static const uint8_t alpha_{name}[] = {{")
        for start in range(0, len(pixels), 24):
            lines.append("    " + ",".join(map(str, pixels[start:start+24])) + ",")
        lines += ["};", f"static const struct desk_glyph glyphs_{name}[] = {{"]
        lines.extend("    {" + ",".join(map(str, g)) + "}," for g in glyphs)
        lines.append("};")
        if density==2:
            lines.append(f"static const struct desk_font_raster raster_{name} = {{glyphs_{name}, alpha_{name}}};")
        else:
            lines.append(f"const struct desk_font desk_font_{name} = {{glyphs_{name}, alpha_{name}, {len(glyphs)}, {ascent}, {ascent+descent+3}, &raster_{name}_2x}};")
    return "\n".join(lines) + "\n"


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--density2-only",action="store_true",help="Preserve the accepted 1x atlas byte-for-byte")
    args=parser.parse_args()
    OUT.with_name("desk_font_2x.inc").write_text(generate(2))
    if not args.density2_only:OUT.write_text(generate(1))


if __name__ == "__main__":
    main()
